def get_history(prompt_id):
    url = f"http://{server_address}:8188/history/{prompt_id}"
    logger.info(f"Getting history from: {url}")
    with urllib.request.urlopen(url) as response:
        return json.loads(response.read())

def run_workflow(ws, prompt):
    """Queue the graph, wait for it to finish and collect videos and texts.

    Returns (videos, texts, error) where videos/texts map node_id -> list and
    error is a human readable string if ComfyUI reported an execution error.
    """
    prompt_id = queue_prompt(prompt)['prompt_id']
    error = None
    while True:
        out = ws.recv()
        if isinstance(out, str):
            message = json.loads(out)
            mtype = message.get('type')
            data = message.get('data') or {}
            if mtype == 'executing':
                if data.get('node') is None and data.get('prompt_id') == prompt_id:
                    break
            elif mtype == 'execution_error' and data.get('prompt_id') == prompt_id:
                error = (f"node {data.get('node_id')} ({data.get('node_type')}): "
                         f"{data.get('exception_type', '')} {data.get('exception_message', '')}").strip()
                logger.error(f"ComfyUI execution error: {error}")
            elif mtype == 'execution_interrupted' and data.get('prompt_id') == prompt_id:
                error = "execution interrupted"
        else:
            continue

    history = get_history(prompt_id).get(prompt_id, {})
    status = history.get('status') or {}
    if error is None and status.get('status_str') == 'error':
        error = "execution failed (see worker logs)"
    output_videos = {}
    output_texts = {}
    for node_id, node_output in history.get('outputs', {}).items():
        videos_output = []
        if 'gifs' in node_output:
            for video in node_output['gifs']:
                # fullpath를 이용하여 직접 파일을 읽고 base64로 인코딩
                with open(video['fullpath'], 'rb') as f:
                    video_data = base64.b64encode(f.read()).decode('utf-8')
                videos_output.append(video_data)
        if videos_output:
            output_videos[node_id] = videos_output
        if 'text' in node_output:
            output_texts[node_id] = [t for t in node_output['text'] if isinstance(t, str)]

    return output_videos, output_texts, error


def get_videos(ws, prompt):
    """Backwards compatible wrapper around run_workflow()."""
    videos, _, _ = run_workflow(ws, prompt)
    return videos


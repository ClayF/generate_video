def _node_model_name(path, models_dir):
    """Mirror the node's to_models_relative_path(): relative to ComfyUI/models when
    the file lives there, otherwise the absolute path (Network Volume)."""
    path = os.path.normpath(path)
    models_dir = os.path.normpath(models_dir)
    if path.startswith(models_dir + os.sep):
        return os.path.relpath(path, models_dir).replace(os.sep, "/")
    return path.replace(os.sep, "/")


def list_local_llm_models(llm_dir=None, extra_dirs=None):
    """GGUF files the Wan Video Prompt Generator would list as 'Local: <name>'.

    Image models come out as 'LLM/<file>', Network Volume models as
    '/runpod-volume/LLM/<file>' — exactly the combo values the node builds.
    """
    llm_dir = llm_dir or LLM_DIR
    dirs = [llm_dir] + list(extra_dirs if extra_dirs is not None else [VOLUME_LLM_DIR])
    models_dir = os.path.dirname(os.path.normpath(llm_dir))
    names = []
    for d in dirs:
        if not d or not os.path.isdir(d):
            continue
        for root, _, files in os.walk(d):
            for f in files:
                lower = f.lower()
                if not lower.endswith(".gguf") or lower.startswith("mmproj") or "qwen" not in lower:
                    continue
                names.append(_node_model_name(os.path.join(root, f), models_dir))
    return sorted(set(names), key=str.lower)


def default_llm_model(llm_dir=None):
    env = os.getenv("PROMPT_EXPANSION_MODEL")
    if env:
        return normalize_llm_model(env)
    models = list_local_llm_models(llm_dir)
    if not models:
        return None
    # Prefer the model the image was configured to fetch (PROMPT_LLM_URL) when
    # several are present, e.g. the stock Qwen3-VL next to the abliterated one
    # on a volume that predates the switch.
    configured = os.path.basename(os.getenv("PROMPT_LLM_URL", "").split("?")[0]).lower()
    for m in models:
        if configured and os.path.basename(m).lower() == configured:
            return f"Local: {m}"
    return f"Local: {models[0]}"


def normalize_llm_model(value):
    """Turn user friendly spellings into the exact combo value the node expects.

    "Local: LLM/x.gguf"          -> unchanged
    "LLM/x.gguf"                 -> "Local: LLM/x.gguf"
    "/runpod-volume/LLM/x.gguf"  -> "Local: /runpod-volume/LLM/x.gguf"
    "x.gguf"                     -> whichever discovered model has that filename,
                                    else "Local: LLM/x.gguf"
    "qwen3.7-plus"               -> unchanged (DashScope cloud model)
    """
    value = str(value).strip()
    if value.startswith("Local: "):
        return value
    if value.lower().endswith(".gguf"):
        if "/" not in value:
            for name in list_local_llm_models():
                if os.path.basename(name).lower() == value.lower():
                    return f"Local: {name}"
            value = f"{os.path.basename(LLM_DIR.rstrip('/'))}/{value}"
        return f"Local: {value}"
    return value


def resolve_prompt_expansion(job_input):
    """Normalise the request's prompt expansion settings.

    Accepted forms:
        "prompt_expansion": true
        "prompt_expansion": {"language": "zh", "model": "...", "device": "GPU", ...}
        "expand_prompt": true                (shorthand)
        "expand_only": true                  (implies expansion; skips video generation)

    Returns None when expansion is off, otherwise a dict with the node inputs.
    """
    raw = job_input.get("prompt_expansion")
    if raw is None:
        raw = job_input.get("expand_prompt")
    expand_only = bool(job_input.get("expand_only", False))
    if raw is None:
        raw = expand_only
    if isinstance(raw, bool):
        raw = {"enabled": raw}
    if not isinstance(raw, dict):
        raise JobError("prompt_expansion must be a boolean or an object")
    enabled = bool(raw.get("enabled", True)) or expand_only
    if not enabled:
        return None

    language = str(raw.get("language", os.getenv("PROMPT_EXPANSION_LANGUAGE", "zh"))).lower()
    if language not in EXPANSION_LANGUAGES:
        raise JobError(f"prompt_expansion.language must be one of {EXPANSION_LANGUAGES}, got {language!r}")

    device = str(raw.get("device", os.getenv("PROMPT_EXPANSION_DEVICE", "GPU"))).upper()
    if device not in EXPANSION_DEVICES:
        raise JobError(f"prompt_expansion.device must be one of {EXPANSION_DEVICES}, got {device!r}")

    model = raw.get("model")
    model = normalize_llm_model(model) if model else default_llm_model()
    if not model:
        raise JobError(f"No local prompt model found in {LLM_DIR} or {VOLUME_LLM_DIR} and no "
                       "prompt_expansion.model / PROMPT_EXPANSION_MODEL given. Let entrypoint.sh download "
                       "the bundled model (needs a Network Volume or PROMPT_LLM_URL), drop a Qwen GGUF plus "
                       "mmproj in the LLM folder, or pass a DashScope model name.")
    if not model.startswith("Local: "):
        key_path = os.path.join(MULTIMODAL_NODE_DIR, "api_key.txt")
        if not os.path.isfile(key_path) or not open(key_path, encoding="utf-8").read().strip():
            raise JobError(f"prompt_expansion.model {model!r} is a DashScope cloud model but no API key is "
                           "configured. Set the DASHSCOPE_API_KEY environment variable on the endpoint.")

    try:
        max_retries = int(raw.get("max_retries", 3))
    except (TypeError, ValueError):
        raise JobError("prompt_expansion.max_retries must be an integer")
    max_retries = min(max(max_retries, 1), 10)

    return {
        "language": language,
        "model": model,
        "mmproj": str(raw.get("mmproj", "(Auto-detect)")),
        "device": device,
        "max_retries": max_retries,
        "save_tokens": bool(raw.get("save_tokens", True)),
    }


def apply_prompt_expansion(prompt, user_prompt, expansion):
    node = prompt[NODE_PROMPT_GENERATOR]["inputs"]
    node["prompt"] = user_prompt
    node["task_type"] = "Image-to-Video"
    node["target_language"] = expansion["language"]
    node["llm_model"] = expansion["model"]
    node["mmproj"] = expansion["mmproj"]
    node["max_retries"] = expansion["max_retries"]
    node["device"] = expansion["device"]
    node["save_tokens"] = expansion["save_tokens"]
    node["image"] = [NODE_RESIZE_START, 0]
    prompt[NODE_TEXT_ENCODE]["inputs"]["positive_prompt"] = [NODE_PROMPT_OUTPUT, 0]
    logger.info(f"Prompt expansion enabled: model={expansion['model']} language={expansion['language']} "
                f"device={expansion['device']}")



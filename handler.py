def build_workflow(job_input, image_path, end_image_path_local, expansion=None):
    """Turn a request into a ComfyUI API-format graph. Pure: no network access."""
    if "prompt" not in job_input:
        raise JobError("'prompt' is required")

    # LoRA 설정 확인 - 배열로 받아서 처리
    lora_pairs = job_input.get("lora_pairs", []) or []
    
    # 최대 4개 LoRA까지 지원
    if len(lora_pairs) > 4:
        logger.warning(f"LoRA 개수가 {len(lora_pairs)}개입니다. 최대 4개까지만 지원됩니다. 처음 4개만 사용합니다.")
        lora_pairs = lora_pairs[:4]
    lora_count = len(lora_pairs)
    
    # 워크플로우 파일 선택 (end_image_*가 있으면 FLF2V 워크플로 사용)
    mode = "flf2v" if end_image_path_local else "i2v"
    workflow_file = os.path.join(WORKFLOW_DIR, WORKFLOW_FILES[(mode, expansion is not None)])
    logger.info(f"Using {'FLF2V' if end_image_path_local else 'single'} workflow ({os.path.basename(workflow_file)}) "
                f"with {lora_count} LoRA pairs")
    
    prompt = load_workflow(workflow_file)
    
    length = job_input.get("length", 81)
    steps = job_input.get("steps", 10)

    prompt[NODE_START_IMAGE]["inputs"]["image"] = comfy_image_ref(image_path)
    prompt["541"]["inputs"]["num_frames"] = length
    prompt[NODE_TEXT_ENCODE]["inputs"]["positive_prompt"] = job_input["prompt"]
    prompt[NODE_TEXT_ENCODE]["inputs"]["negative_prompt"] = job_input.get("negative_prompt", DEFAULT_NEGATIVE_PROMPT)
    seed = job_input.get("seed", 42)
    prompt["220"]["inputs"]["seed"] = seed
    prompt["540"]["inputs"]["seed"] = seed
    prompt["540"]["inputs"]["cfg"] = job_input.get("cfg", 2.0)
    # 해상도(폭/높이) 16배수 보정
    original_width = job_input.get("width", 480)
    original_height = job_input.get("height", 832)
    adjusted_width = to_nearest_multiple_of_16(original_width)
    adjusted_height = to_nearest_multiple_of_16(original_height)
    if adjusted_width != original_width:
        logger.info(f"Width adjusted to nearest multiple of 16: {original_width} -> {adjusted_width}")
    if adjusted_height != original_height:
        logger.info(f"Height adjusted to nearest multiple of 16: {original_height} -> {adjusted_height}")
    prompt[NODE_WIDTH]["inputs"]["value"] = adjusted_width
    prompt[NODE_HEIGHT]["inputs"]["value"] = adjusted_height
    prompt["498"]["inputs"]["context_overlap"] = job_input.get("context_overlap", 48)
    prompt["498"]["inputs"]["context_frames"] = length

    # step 설정 적용
    if "834" in prompt:
        prompt["834"]["inputs"]["steps"] = steps
        logger.info(f"Steps set to: {steps}")
        lowsteps = int(steps*0.6)
        prompt["829"]["inputs"]["step"] = lowsteps
        logger.info(f"LowSteps set to: {lowsteps}")

    # 엔드 이미지가 있는 경우 617번 노드에 경로 적용 (FLF2V 전용)
    if end_image_path_local:
        prompt[NODE_END_IMAGE]["inputs"]["image"] = comfy_image_ref(end_image_path_local)
    
    # LoRA 설정 적용 - HIGH LoRA는 노드 279, LOW LoRA는 노드 553
    if lora_count > 0:
        # HIGH LoRA 노드 (279번)
        high_lora_node_id = "279"
        
        # LOW LoRA 노드 (553번)
        low_lora_node_id = "553"
        
        # 입력받은 LoRA pairs 적용 (lora_1부터 시작)
        for i, lora_pair in enumerate(lora_pairs):
            if i < 4:  # 최대 4개까지만
                lora_high = lora_pair.get("high")
                lora_low = lora_pair.get("low")
                lora_high_weight = lora_pair.get("high_weight", 1.0)
                lora_low_weight = lora_pair.get("low_weight", 1.0)
                
                # HIGH LoRA 설정 (노드 279번, lora_1부터 시작)
                if lora_high:
                    prompt[high_lora_node_id]["inputs"][f"lora_{i+1}"] = lora_high
                    prompt[high_lora_node_id]["inputs"][f"strength_{i+1}"] = lora_high_weight
                    logger.info(f"LoRA {i+1} HIGH applied to node 279: {lora_high} with weight {lora_high_weight}")
                
                # LOW LoRA 설정 (노드 553번, lora_1부터 시작)
                if lora_low:
                    prompt[low_lora_node_id]["inputs"][f"lora_{i+1}"] = lora_low
                    prompt[low_lora_node_id]["inputs"][f"strength_{i+1}"] = lora_low_weight
                    logger.info(f"LoRA {i+1} LOW applied to node 553: {lora_low} with weight {lora_low_weight}")

    # 프롬프트 확장 (WanVideoPromptGenerator -> GVPromptOutput -> TextEncode)
    if expansion is not None:
        apply_prompt_expansion(prompt, job_input["prompt"], expansion)

    return prompt


def wait_for_comfyui():
    ws_url = f"ws://{server_address}:8188/ws?clientId={client_id}"
    logger.info(f"Connecting to WebSocket: {ws_url}")
    
    # 먼저 HTTP 연결이 가능한지 확인
    http_url = f"http://{server_address}:8188/"
    logger.info(f"Checking HTTP connection to: {http_url}")
    
    # HTTP 연결 확인 (최대 1분)
    max_http_attempts = 180
    for http_attempt in range(max_http_attempts):
        try:
            response = urllib.request.urlopen(http_url, timeout=5)
            logger.info(f"HTTP 연결 성공 (시도 {http_attempt+1})")
            break
        except Exception as e:
            logger.warning(f"HTTP 연결 실패 (시도 {http_attempt+1}/{max_http_attempts}): {e}")
            if http_attempt == max_http_attempts - 1:
                raise Exception("ComfyUI 서버에 연결할 수 없습니다. 서버가 실행 중인지 확인하세요.")
            time.sleep(1)
    
    ws = websocket.WebSocket()
    # 웹소켓 연결 시도 (최대 3분)
    max_attempts = int(180/5)  # 3분 (1초에 한 번씩 시도)
    for attempt in range(max_attempts):
        try:
            ws.connect(ws_url)
            logger.info(f"웹소켓 연결 성공 (시도 {attempt+1})")
            break
        except Exception as e:
            logger.warning(f"웹소켓 연결 실패 (시도 {attempt+1}/{max_attempts}): {e}")
            if attempt == max_attempts - 1:
                raise Exception("웹소켓 연결 시간 초과 (3분)")
            time.sleep(5)
    return ws


def handler(job):
    job_input = job.get("input", {})

    # Never log base64 payloads in full
    logger.info("Received job input: " + json.dumps(
        {k: (f"<{len(v)} chars>" if isinstance(v, str) and len(v) > 200 else v) for k, v in job_input.items()},
        ensure_ascii=False, default=str))
    task_id = f"task_{uuid.uuid4()}"

    try:
        # 이미지 입력 처리 (image_path, image_url, image_base64 중 하나만 사용)
        image_path = None
        if "image_path" in job_input:
            image_path = process_input(job_input["image_path"], task_id, "input_image.jpg", "path")
        elif "image_url" in job_input:
            image_path = process_input(job_input["image_url"], task_id, "input_image.jpg", "url")
        elif "image_base64" in job_input:
            image_path = process_input(job_input["image_base64"], task_id, "input_image.jpg", "base64")
        else:
            # 기본값 사용
            image_path = process_input(DEFAULT_IMAGE, task_id, "input_image.png", "path")
            logger.info(f"기본 이미지 파일을 사용합니다: {DEFAULT_IMAGE}")

        # 엔드 이미지 입력 처리 (end_image_path, end_image_url, end_image_base64 중 하나만 사용)
        end_image_path_local = None
        if "end_image_path" in job_input:
            end_image_path_local = process_input(job_input["end_image_path"], task_id, "end_image.jpg", "path")
        elif "end_image_url" in job_input:
            end_image_path_local = process_input(job_input["end_image_url"], task_id, "end_image.jpg", "url")
        elif "end_image_base64" in job_input:
            end_image_path_local = process_input(job_input["end_image_base64"], task_id, "end_image.jpg", "base64")

        expansion = resolve_prompt_expansion(job_input)
        expand_only = bool(job_input.get("expand_only", False))

        prompt = build_workflow(job_input, image_path, end_image_path_local, expansion)
        if expand_only:
            prompt = expand_only_graph(prompt)
            logger.info("expand_only: running prompt expansion without video generation")

        ws = wait_for_comfyui()
        try:
            videos, texts, error = run_workflow(ws, prompt)
        finally:
            ws.close()

        expanded_prompt = None
        if expansion is not None:
            for t in texts.get(NODE_PROMPT_OUTPUT, []):
                expanded_prompt = t
                break

        if expand_only:
            if expanded_prompt is None:
                raise JobError(error or "Prompt expansion produced no text")
            logger.info(f"Expanded prompt: {expanded_prompt}")
            return {"expanded_prompt": expanded_prompt, "prompt": job_input["prompt"]}

        # 이미지가 없는 경우 처리
        for node_id in videos:
            if videos[node_id]:
                result = {"video": videos[node_id][0]}
                if expansion is not None:
                    result["expanded_prompt"] = expanded_prompt
                    result["prompt"] = job_input["prompt"]
                return result

        raise JobError(error or "Video not found in ComfyUI output")

    except JobError as e:
        logger.error(f"Job failed: {e}")
        return {"error": str(e)}
    finally:
        # staged input images are per job; don't let them pile up in ComfyUI/input
        shutil.rmtree(task_input_dir(task_id), ignore_errors=True)


if __name__ == "__main__":
    runpod.serverless.start({"handler": handler})
